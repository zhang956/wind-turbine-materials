import assert from 'node:assert/strict';
import * as THREE from 'three';
import {buildStorage,mountStorage} from '../viewer/storage.js';
const model=buildStorage();
for(const name of ['电池舱','储能PCS','储能变压器'])assert.ok(model.group.getObjectByName(name),name);
assert.ok(new THREE.Box3().setFromObject(model.group).min.z>=0);
model.setMode('charge');
assert.ok(model.arrows.every(a=>a.visible));
const charge=model.arrows.map(a=>a.quaternion.clone());
model.setMode('discharge');
assert.ok(model.arrows.every((a,i)=>Math.abs(a.quaternion.dot(charge[i]))<.01),'Flow reverses on every segment');
model.setMode('idle');assert.ok(model.arrows.every(a=>!a.visible));
model.setMode('bad');assert.ok(model.arrows.every(a=>!a.visible));
const elements=new Map();
globalThis.document={getElementById(id){if(!elements.has(id))elements.set(id,{value:'idle',checked:false,disabled:true,textContent:''});return elements.get(id)}};
let focused=null;const scene=new THREE.Scene();
const panel=mountStorage({scene,focus(group){focused=group}});
const $=id=>document.getElementById(id);
$('storageFocus').onclick();assert.equal(focused,panel.group);
$('storageMode').value='charge';$('storageMode').onchange();
assert.ok($('storageStatus').textContent.includes('充电'));
$('storageTransparent').checked=true;$('storageTransparent').onchange();
assert.equal(panel.group.getObjectByName('电池舱').material.opacity,.18);
panel.setVisible(false);assert.equal(panel.group.visible,false);
panel.reset();assert.equal($('storageMode').value,'idle');assert.equal(panel.group.getObjectByName('电池舱').material.opacity,1);
console.log('PASS: storage equipment, reversible flow, idle, focus, transparency, visibility and reset');
let elapsed=0,epoch=0,replaying=false;
const integrated=mountStorage({scene:new THREE.Scene(),focus(){},simulation:{getClock:()=>({elapsed,epoch}),getState:()=>({electricPower:1e6}),get isReplaying(){return replaying;}}});
$('storageMode').value='charge';$('storageMode').onchange();elapsed=100;integrated.tick();
const charged=integrated.getSnapshot();assert.ok(charged.energy.energyMWh>1);
integrated.tick();assert.deepEqual(integrated.getSnapshot(),charged,'Same simulated clock never integrates twice');
integrated.setVisible(false);elapsed=200;integrated.tick();assert.ok(integrated.getSnapshot().energy.energyMWh>charged.energy.energyMWh,'Hidden equipment still stores energy');
const live=integrated.getSnapshot();replaying=true;integrated.showReplay(charged);elapsed=999;integrated.tick();assert.deepEqual(integrated.getSnapshot(),live,'Replay does not mutate stored energy');replaying=false;elapsed=200;integrated.exitReplay();
epoch++;elapsed=0;integrated.tick();assert.equal(integrated.getSnapshot().energy.energyMWh,1);assert.equal(integrated.getSnapshot().mode,'idle');assert.equal(integrated.getSnapshot().energy.chargedMWh,0);
console.log('PASS: clock freeze, hidden integration, read-only replay, epoch reset');
